def extract_greeting(
    message
):

    text = str(
        message
    ).strip()

    lower = text.lower()

    for greeting in GREETING_WORDS:

        if lower.startswith(
            greeting.lower()
        ):

            remainder = text[
                len(greeting):
            ].strip()

            return (
                greeting,
                remainder
            )

    return (
        None,
        text
    )


