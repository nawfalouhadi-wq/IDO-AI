def ask_groq(message):

    if not GROQ_API_KEY:
        return None

    if not message:
        return None

    if not provider_available(
        "GROQ"
    ):
        return None

    try:

        print(
            "Trying PRIMARY AI: Groq..."
        )

        system_prompt = """
You are Ido AI.

You are the primary AI assistant.

Always answer the user's actual request.

If the user begins with a greeting such as:
السلام عليكم
مرحبا
سلام
hello
hi

and then asks a real question or gives a real request,
do NOT stop at the greeting.

Reply naturally to the greeting first and then answer
the actual request.

Example:

User:
السلام عليكم، ما هي عاصمة المغرب؟

Good:
وعليكم السلام ورحمة الله وبركاته.
عاصمة المغرب هي الرباط.

Bad:
وعليكم السلام، كيف يمكنني مساعدتك؟

Never replace a real request with a generic greeting.

You are multilingual and should normally answer
in the same language used by the user.

Do not claim that you generated an image if no image
was actually generated by the application.
"""

        response = requests.post(

            GROQ_URL,

            headers={
                "Authorization":
                    f"Bearer {GROQ_API_KEY}",

                "Content-Type":
                    "application/json"
            },

            json={

                "model":
                    GROQ_MODEL,

                "messages": [

                    {
                        "role":
                            "system",

                        "content":
                            system_prompt
                    },

                    {
                        "role":
                            "user",

                        "content":
                            message
                    }
                ],

                "temperature":
                    0.7,

                "max_completion_tokens":
                    2048
            },

            timeout=REQUEST_TIMEOUT
        )

        print(
            "Groq Status:",
            response.status_code
        )

        if response.status_code != 200:

            print(
                "Groq Response:",
                response.text[:1500]
            )

            provider_failure(
                "GROQ",
                response.status_code
            )

            return None

        data = request_json(
            response,
            "Groq"
        )

        if not data:
            return None

        choices = data.get(
            "choices",
            []
        )

        if not choices:
            return None

        message_data = (
            choices[0].get(
                "message",
                {}
            )
        )

        content = message_data.get(
            "content"
        )

        answer = clean_answer(
            content
        )

        if answer:

            print(
                "PRIMARY AI SUCCESS: GROQ"
            )

            return answer

        return None

    except requests.exceptions.Timeout:

        print(
            "Groq ERROR: timeout."
        )

        return None

    except requests.exceptions.ConnectionError:

        print(
            "Groq ERROR: connection failed."
        )

        return None

    except Exception as exc:

        print(
            "Groq ERROR:",
            exc
        )

        return None


