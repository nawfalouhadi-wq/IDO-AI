def get_response(
    message,
    conversation_id=None
):

    if not message:

        return (
            "اكتب رسالة أولًا."
        )

    original_message = str(
        message
    ).strip()

    if not original_message:

        return (
            "اكتب رسالة أولًا."
        )


    # ========================================================
    # IMAGE GENERATION
    # ========================================================

    if is_image_generation_request(
        original_message
    ):

        prompt = get_image_prompt(
            original_message
        )

        return generate_image(
            prompt
        )


    # ========================================================
    # GREETING + REAL QUESTION
    # ========================================================

    greeting, remainder = extract_greeting(
        original_message
    )

    if greeting and remainder:

        print(
            "GREETING + REAL REQUEST DETECTED"
        )

        # لا نعيد quick response.
        #
        # نرسل الطلب الحقيقي إلى Groq.
        #

        answer = ask_groq(
            remainder
        )

        if answer:

            if greeting.startswith(
                "السلام"
            ):

                return (
                    "وعليكم السلام ورحمة الله وبركاته.\n\n"
                    + answer
                )

            return (
                "مرحبًا بك.\n\n"
                + answer
            )


    # ========================================================
    # PRIMARY AI
    # ========================================================

    answer = ask_groq(
        original_message
    )

    if answer:

        print(
            "TEXT ROUTE SUCCESS: GROQ"
        )

        return answer


    # ========================================================
    # FALLBACKS
    # ========================================================

    fallback_routes = [

        (
            "MISTRAL",
            ask_mistral
        ),

        (
            "OPENROUTER",
            ask_openrouter
        ),

        (
            "XAI",
            ask_xai
        ),

        (
            "POLLINATIONS",
            ask_pollinations
        )
    ]


    for name, function in fallback_routes:

        if not provider_available(
            name
        ):

            print(
                f"{name}: SKIPPED"
            )

            continue

        try:

            answer = function(
                original_message
            )

        except Exception as exc:

            print(
                f"{name} ROUTER ERROR:",
                exc
            )

            answer = None

        if answer:

            print(
                f"TEXT FALLBACK SUCCESS: {name}"
            )

            return answer


    return (
        "أنا Ido AI، لكن لم أتمكن من "
        "الوصول إلى أي مزود ذكاء اصطناعي "
        "حاليًا."
    )


